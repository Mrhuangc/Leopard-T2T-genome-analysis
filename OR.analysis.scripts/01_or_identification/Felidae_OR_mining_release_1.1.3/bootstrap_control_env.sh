#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ENV_FILE="$SCRIPT_DIR/environment.control.yml"
ENV_NAME="felidae-or-control"

if command -v mamba >/dev/null 2>&1; then
    SOLVER="mamba"
elif command -v conda >/dev/null 2>&1; then
    SOLVER="conda"
else
    echo "ERROR: mamba or conda is required." >&2
    exit 1
fi

if "$SOLVER" env list | awk '{print $1}' | grep -Fxq "$ENV_NAME"; then
    "$SOLVER" env update -n "$ENV_NAME" -f "$ENV_FILE" --prune
else
    "$SOLVER" env create -f "$ENV_FILE"
fi

ENV_PREFIX="$($SOLVER env list | awk -v name="$ENV_NAME" '$1 == name {print $NF; exit}')"
[[ -n "$ENV_PREFIX" && -d "$ENV_PREFIX" ]] || {
    echo "ERROR: failed to resolve environment prefix for $ENV_NAME" >&2
    exit 1
}

# Remove metadata generated by an older editable installation. It must never be
# shipped as source because it can preserve obsolete dependency requirements.
find "$SCRIPT_DIR/src" -maxdepth 1 -type d -name '*.egg-info' -exec rm -rf -- {} +

# All third-party dependencies are installed above by the Conda solver.  Pip
# installs only this local package and must not resolve/build NumPy or other
# compiled dependencies with the legacy host compiler.
"$ENV_PREFIX/bin/python" -m pip install \
    --no-deps \
    --no-build-isolation \
    -e "$SCRIPT_DIR"

"$ENV_PREFIX/bin/java" -version
"$ENV_PREFIX/bin/nextflow" -version
"$ENV_PREFIX/bin/python" --version
"$ENV_PREFIX/bin/nf-test" version

echo
echo "Control environment is ready: $ENV_PREFIX"
echo "Activate it with: conda activate $ENV_NAME"
