#!/usr/bin/env bash
REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
AUX="${REPO_ROOT}/scripts"

#run TRASH2
Rscript path/TRASH_2/src/TRASH.R -o path/to/outdir/TRASH2_new -p 20 -m 2000 -f path/PPA.final.genome.fna
sed 's/^M/\n/g' PPA.final.genome.fna_repeats.gff > PPA.final.genome.fna_repeats1.gff
cut -f 1,4-5 PPA.final.genome.fna_repeats1.gff > PPA.TRASH2.bed

#Obtaining Hi-C interaction strength results from Centromics software output.

#Obtain the breakpoint regions by aligning with the domestic dog genome.
minimap2 -t 30 -x asm20 path/PPA.final.genome.fna path/CFA.genome.GCA_044048985.fna > PPA.CFA.minimap2.paf
perl ~/software/NGenomeSyn/bin/GetTwoGenomeSyn.pl Paf2Link PPA.CFA.minimap2.paf 100000 PPA.CFA.minimap2.link
sort -k4,4 -k5,5n -k6,6n PPA.CFA.minimap2.link > PPA.CFA.minimap2.sort.link

#predict centromere region
#PPA.cor.breakpoint.region.bed  Synteny breakpoint regions manually picked from PPA.CFA.minimap2.sort.link, with the format chr	start	end.
#PPA_carnivora.filteredRepeats.bed  earlgrey result
#PPA.CL1.merge.bed  SAT113 annotation results manually selected from TRASH2 output, in the format chr	start	end.
python "${AUX}/predict_centromere_region.py" \
  --fai PPA.final.genome.fna.fai \
  --repeat-bed path/PPA_carnivora.filteredRepeats.bed \
  --trash-bed PPA.TRASH2.bed \
  --cl113-bed PPA.CL1.merge.bed \
  --hic hic_inter.density.convert.txt \
  --breakpoint-bed PPA.cor.breakpoint.region.bed \
  --window-size 20000 \
  --step-size 10000 \
  --boundary-pad 10000 \
  --merge-gap 10000 \
  --output-prefix PPA.centromere

#Manually check whether the centromere predictions are reasonable by combining them with the heatmap generated by moddotplot.

#plot evidence
#PPA.CL2.TRASH2.bed  SAT483 annotation results
python "${AUX}/plot_centromere_evidence_fixed.py" \
  --hic hic_inter.density.convert.txt \
  --repeat-bed path/PPA_carnivora.filteredRepeats.bed \
  --cl1-bed PPA.CL1.merge.bed \
  --cl2-bed PPA.CL2.TRASH2.bed \
  --breakpoint-bed PPA.cor.breakpoint.region.bed \
  --trash-bed PPA.TRASH2.bed \
  --fai PPA.final.genome.fna.fai \
  --cen-bed PPA.centromere.region.bed \
  --window-size 20000 \
  --step-size 10000 \
  --hic-low-q 0.05 \
  --outdir PPA_centromere_plot

#QV
genome=path/PPA.final.genome.fna
hifi_reads=path/huabao.hifi.fastq.gz
R1=path/PPA.MGI_1.filtered.fq.gz
R2=path/PPA.MGI_2.filtered.fq.gz
sp=PPA

bedtools getfasta -fi $genome -bed PPA.centromere.region.bed -fo PPA.centromere.region.fasta

meryl k=21 threads=20 memory=24g count output HiFi.meryl $hifi_reads && echo "count done" 
meryl greater-than 1 HiFi.meryl output HiFi.gt1.meryl && echo "filter done" 
meryl k=21 threads=8 memory=24g count output ${R1}.meryl $R1 && echo "1 done" 
meryl k=21 threads=8 memory=24g count output ${R2}.meryl $R2 && echo "2 done" 
meryl threads=8 memory=24g union-sum output $sp.ngs.meryl ${R1}.meryl ${R2}.meryl && echo "all done" 
meryl greater-than 1 $sp.ngs.meryl output $sp.ngs.gt1.meryl && echo "filter done"

meryl threads=20 memory=24g union-sum output $sp.hybrid.meryl HiFi.gt1.meryl $sp.ngs.gt1.meryl  && echo "merge done"

merqury.sh $sp.hybrid.meryl PPA.centromere.region.fasta PPA.centromere

#GCI
mat_merylDB=merylDB
mat_asm=path/PPA.final.genome.fna
mat_hifi=path/huabao.hifi.fastq.gz
mat_ont=path/pass.ul.fq.gz
mat=PPA
threads=40

meryl count k=15 output $mat_merylDB $mat_asm
meryl print greater-than distinct=0.9998 $mat_merylDB > repetitive_k15.txt
winnowmap -W repetitive_k15.txt -ax map-pb $mat_asm $mat_hifi > ${mat}.winnowmap.hifi.sam
samtools view -@ $threads -Sb ${mat}.winnowmap.hifi.sam | samtools sort -@ $threads -o ${mat}.winnowmap.hifi.bam
samtools index ${mat}.winnowmap.hifi.bam
samtools flagstat -@ 30 ${mat}.winnowmap.hifi.bam > ${mat}.winnowmap.hifi.bam.stats
paftools.js sam2paf ${mat}.winnowmap.hifi.sam | sort -k6,6V -k8,8n > ${mat}.winnowmap.hifi.paf
rm ${mat}.winnowmap.hifi.sam

winnowmap -W repetitive_k15.txt -ax map-ont $mat_asm $mat_ont > ${mat}.winnowmap.ont.sam
samtools view -@ $threads -Sb ${mat}.winnowmap.ont.sam | samtools sort -@ $threads -o ${mat}.winnowmap.ont.bam
samtools index ${mat}.winnowmap.ont.bam
samtools flagstat -@ 30 ${mat}.winnowmap.ont.bam > ${mat}.winnowmap.ont.bam.stats
paftools.js sam2paf ${mat}.winnowmap.ont.sam | sort -k6,6V -k8,8n > ${mat}.winnowmap.ont.paf
rm ${mat}.winnowmap.ont.sam

minimap2 -t $threads -ax map-hifi $mat_asm $mat_hifi > ${mat}.minimap2.hifi.sam
samtools view -@ $threads -Sb ${mat}.minimap2.hifi.sam | samtools sort -@ $threads -o ${mat}.minimap2.hifi.bam
samtools index -c ${mat}.minimap2.hifi.bam ## this is necessary!!!
paftools.js sam2paf ${mat}.minimap2.hifi.sam | sort -k6,6V -k8,8n > ${mat}.minimap2.hifi.paf
rm ${mat}.minimap2.hifi.sam

minimap2 -t $threads -ax map-ont $mat_asm $mat_ont > ${mat}.minimap2.ont.sam
samtools view -@ $threads -Sb ${mat}.minimap2.ont.sam | samtools sort -@ $threads -o ${mat}.minimap2.ont.bam
samtools index -c ${mat}.minimap2.ont.bam ## this is necessary!!!
paftools.js sam2paf ${mat}.minimap2.ont.sam | sort -k6,6V -k8,8n > ${mat}.minimap2.ont.paf
rm ${mat}.minimap2.ont.sam

bedtools slop -b 2000000 -i PPA.centromere.region.bed -g path/PPA.final.genome.fna.fai > PPA.centromere.region.slop.2MB.bed
GCI -r $mat_asm --hifi ${mat}.winnowmap.hifi.bam ${mat}.minimap2.hifi.paf --nano ${mat}.winnowmap.ont.bam ${mat}.minimap2.ont.paf -t 16 -p -f -it pdf --regions PPA.centromere.region.slop.2MB.bed

#NucFreq
bedtools slop -b 500000 -i PPA.centromere.region.bed -g path/PPA.final.genome.fna.fai > PPA.centromere.region.slop.500K.bed
awk 'BEGIN{OFS="\t"}{
  print $1,$2,$3,$1"_"$2"_"$3
}' PPA.centromere.region.slop.500K.bed \
> PPA.centromere.region.slop.500K.1.bed

meryl count k=15 output merylDB path/PPA.final.genome.fna
meryl print greater-than distinct=0.9998 merylDB > repetitive_k15.txt
winnowmap -W ./repetitive_k15.txt --MD -Ha -x map-pb -t 40 path/PPA.final.genome.fna path/huabao.hifi.fastq.gz | samtools view -@ 8 -b -F 2308 - | samtools sort -@ 8 -o PPA.primary.sort.bam -
samtools index -@ 8 PPA.primary.sort.bam

NUCFREQ=path/NucFreq/NucPlot.py
BAM=PPA.primary.sort.bam

mkdir -p bed obed plots
: > plot.NucFreq.sh  # start a fresh command file on each run
while read chr start end name
do
    echo -e "${chr}\t${start}\t${end}" \
      > bed/${name}.bed

    echo "python ${NUCFREQ} --bed bed/${name}.bed --obed obed/${name}.nucfreq.bed --minobed 2 --legend -s -c 1000 --width 20 --height 4 --dpi 300 -t 8 ${BAM} plots/${name}.nucfreq.png" \
      >> plot.NucFreq.sh

done < PPA.centromere.region.slop.500K.1.bed

bash plot.NucFreq.sh

#StainedGlass
bed=PPA.centromere.region.slop.500K.bed
genome=path/PPA.final.genome.fna
prefix=PPA

bedtools getfasta -fi $genome -bed $bed -fo $prefix.centromere.fasta
python "${AUX}/split_fasta_by_records.py" -i $prefix.centromere.fasta -o $prefix.centromere.fasta.split -n 5 -p ${prefix}_cen

SG=path/StainedGlass  #StainedGlass dir
SG_ENV=path/StainedGlass/.snakemake/conda

for fa in $prefix.centromere.fasta.split/*.fa
do
    sample=$(basename "${fa}" .fa)
    samtools faidx ${fa}

    snakemake \
      -s "${SG}/workflow/Snakefile" \
      --configfile path/to/StainedGlass/base.yaml \
      --config sample="${sample}" fasta="$(readlink -f "${fa}")" \
      --cores 24 \
      --conda-prefix "${SG_ENV}" \
      make_figures \
      -p

done
